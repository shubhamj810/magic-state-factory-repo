def weak_ok(S, M):
    """check the weak-factory conditions; return list of violations."""
    bad = []
    for i, m in enumerate(M):
        for a, s in enumerate(S):
            if wt(s & m) & 1:
                bad.append(("s.m", a, i))
            for b in range(a + 1, len(S)):
                if wt(s & S[b] & m) & 1:
                    bad.append(("ssm", a, b, i))
            for j in range(i + 1, len(M)):
                if wt(s & m & M[j]) & 1:
                    bad.append(("smm", a, i, j))
    return bad


def form(M):
    k = len(M)
    out = {}
    for i in range(k):
        for j in range(i, k):
            for l in range(j, k):
                out[(i, j, l)] = wt(M[i] & M[j] & M[l]) & 1
    return out


def double(S, M, ns, Ct, L, nt):
    """the doubled factory as (cols, k, N)."""
    assert len(M) == len(L)
    k = len(M)
    fs, ft = form(M), form(L)
    if fs != ft:
        raise ValueError("forms differ: %s vs %s" % (fs, ft))
    o2, o3 = ns, 2 * ns
    outs = [m | (m << o2) | (l << o3) for m, l in zip(M, L)]
    chks = [s | (s << o2) for s in S] + [c << o3 for c in Ct] + [(m << o2) | (l << o3) for m, l in zip(M, L)]
    chks = basis(chks)
    wires = outs + chks
    n = 2 * ns + nt
    return {"columns": cols_from_rows(wires, n), "k": k, "N": len(wires), "n": n}


