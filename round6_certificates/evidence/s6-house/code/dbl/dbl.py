def golay_weak(copies=1):
    """direct sum of `copies` Golay weak factories ([[23,1,7]] each): S = even subcodes, m_i = 1 on block i."""
    G, E = golay23()
    S, M = [], []
    for c in range(copies):
        S += shift_rows(E, 23 * c)
        M.append(((1 << 23) - 1) << (23 * c))
    return S, M, 23 * copies
