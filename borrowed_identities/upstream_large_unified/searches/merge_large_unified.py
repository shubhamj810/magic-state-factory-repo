"""Merge the slices of searches/large_unified.py into catalogue files and print progress.

From finished slices only (every row complete), writes:
  outputs/large_unified_factories.csv        every distinct factory, l=2,3,4: search stage, stages run, no Quirk link
  outputs/large_unified_factories_l3.csv     the l=3 rows alone
  outputs/large_unified_with_quirk.csv.zip   the same as the first file, with a Quirk link per row
  outputs/large_unified_smallest.csv         smallest factory per output class (l, k, Clifford-reduced output),
                                             with its search stage and Quirk link
Factories differing only by an l=4 sign pattern that leaves the size and the output unchanged are counted once.
Prints, per level, factories, classes by [[n,k]] and output, output gates, which stage gave the smallest factory
of each class, and slice progress. Safe to run while the sweep is going. Run: python3 searches/merge_large_unified.py
"""
import csv, glob, os, re, sys, zipfile
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
SL = os.path.join(ROOT, "outputs", "large_unified")
OUTD = os.path.join(ROOT, "outputs")
csv.field_size_limit(sys.maxsize)
GLUE_KMAX = 9
NMAX = {2: 18, 3: 18, 4: 16}
KMAX = 12
KMAX_LEVEL = {2: 12, 3: 12, 4: 8}               # l=4 stops at k=8: at k=9 its gluing stage (4 check qubits) does not finish
F = ["l", "k", "n", "N", "d", "search_stage", "stages_run", "params", "reduced", "raw", "zcount", "essential_dim", "frame_exact"]


def circuit(r):
    """Rebuild the factory's gates from its stage and parameters (deterministic, as in the search)."""
    import unified_search as us
    from Two_group import build_gate_set, find_valid_signs
    L, k, N = int(r["l"]), int(r["k"]), int(r["N"])
    if r["search_stage"] == "two-group":
        st, so = (int(x.split("=")[1]) for x in r["params"].split(","))
        pairs, _, _ = build_gate_set(k, N - k, st, so)
        sigmas = [{p: 1 for p in pairs}] if L <= us.SIGN_FREE_MAX_L else find_valid_signs(L, N, k, pairs)
        for sg in sigmas:                          # at l=4 pick the sign pattern that gives this row's output
            g = us.two_group_gates(k, N - k, sg)
            if L <= us.SIGN_FREE_MAX_L:
                return g
            info = us.classify_factory(dict(stage="x", k=k, r=N - k, gates=g, params=""), L)
            if info and info["raw"] == r["raw"]:
                return g
        return None
    from symfree_search import solve_binding
    sol = solve_binding([int(b) for b in r["params"].split("=")[1].split("+")], N - k, L)
    return [(frozenset(S), c % (1 << L)) for S, c in sol["gates"]] if sol else None


QUIRK_NMAX = 14                                  # Quirk links only up to this many circuit qubits (larger ones are
                                                 # megabyte URLs Quirk cannot display); every factory gets a gate list


def quirk(r):
    import unified_search as us
    if int(r["N"]) > QUIRK_NMAX:
        return ""
    g = circuit(r)
    return us.quirk_url(g, int(r["N"]), int(r["l"]), k=int(r["k"])) if g else ""


GATE_LIST_NMAX = 14                              # two-group circuits above this are not stored: they are fixed by
                                                 # (k, N, s_total, s_O) and regenerated by regenerate_circuit()


def regenerate_circuit(l, k, N, params, stage="two-group", raw=None):
    """The exact gate list of any catalogue factory from its CSV row: (support, coefficient) pairs, Z(c*pi/2^l)."""
    return circuit(dict(l=str(l), k=str(k), N=str(N), params=params, search_stage=stage, raw=raw or ""))


def write_gate_lists(rows, L):
    """outputs/large_unified_l{L}_circuits.txt.zip: explicit gate lists, one block per stored CSV row,
    '# row l k n N stage params' then one line per rotation 'q,q,...:c' meaning Z(c*pi/2^l) on those qubits
    (outputs are qubits 0..k-1). Gluing circuits are always stored; two-group circuits only up to N=14."""
    path = os.path.join(OUTD, f"large_unified_l{L}_circuits.txt")
    with open(path, "w") as fh:
        for i, r in enumerate(rows):
            if r["search_stage"] == "two-group" and int(r["N"]) > GATE_LIST_NMAX:
                continue
            g = circuit(r)
            fh.write(f"# {i} l={r['l']} k={r['k']} n={r['n']} N={r['N']} {r['search_stage']} {r['params']}\n")
            for S, c in (g or []):
                fh.write(",".join(map(str, sorted(S))) + f":{c}\n")
    with zipfile.ZipFile(path + ".zip", "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        z.write(path, os.path.basename(path))
    os.remove(path)


def write(path, rows, fields):
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore"); w.writeheader(); w.writerows(rows)


def main(with_quirk=True, quirk_levels=("2", "3", "4")):
    rows, status, seen = [], {}, set()
    for f in glob.glob(os.path.join(SL, "l*_k*.csv")):
        L, k = map(int, re.findall(r"l(\d)_k(\d+)\.csv$", f)[0])
        if k > KMAX_LEVEL[L]:
            continue
        done = os.path.exists(f + ".done")
        status[(L, k)] = done
        if not done:
            continue
        for r in csv.DictReader(open(f)):
            key = (r["l"], r["k"], r["n"], r["N"], r["search_stage"], r["params"], r["raw"])
            if key in seen:
                continue                            # same factory reached by another l=4 sign pattern
            seen.add(key)
            r["stages_run"] = "two-group+gluing" if k <= GLUE_KMAX else "two-group only"
            r["gate_list_id"] = ""
            rows.append({x: r.get(x, "") for x in F})
    rows.sort(key=lambda r: (int(r["l"]), int(r["k"]), int(r["n"]), int(r["N"])))
    best = {}
    for r in rows:
        key = (r["l"], r["k"], r["reduced"])
        if key not in best or (int(r["n"]), int(r["N"])) < (int(best[key]["n"]), int(best[key]["N"])):
            best[key] = r
    small = sorted(best.values(), key=lambda r: (int(r["l"]), int(r["k"]), int(r["n"])))
    write(os.path.join(OUTD, "large_unified_factories.csv"), rows, F)
    write(os.path.join(OUTD, "large_unified_factories_l3.csv"), [r for r in rows if r["l"] == "3"], F)
    if with_quirk:
        cache = os.path.join(SL, "quirk_cache.csv")
        known = {}
        if not os.path.exists(cache):
            with open(cache, "w", newline="") as fh:
                csv.writer(fh).writerow(["l", "k", "n", "N", "search_stage", "params", "raw", "quirk"])
        if os.path.exists(cache):
            known = {(c["l"], c["k"], c["n"], c["N"], c["search_stage"], c["params"], c["raw"]): c["quirk"] for c in csv.DictReader(open(cache))}
        for r in rows:
            key = (r["l"], r["k"], r["n"], r["N"], r["search_stage"], r["params"], r["raw"])
            if r["l"] not in quirk_levels or int(r["N"]) > QUIRK_NMAX:
                r["quirk"] = known.get(key, "") if int(r["N"]) <= QUIRK_NMAX else ""
                continue
            r["quirk"] = known.get(key) or quirk(r)
            known[key] = r["quirk"]
            with open(cache, "a", newline="") as fh:   # save each link as it is made, so an interruption keeps them
                csv.writer(fh).writerow(list(key) + [r["quirk"]])
        tmp = os.path.join(OUTD, "large_unified_with_quirk.csv")
        write(tmp, rows, F + ["quirk"])
        with zipfile.ZipFile(tmp + ".zip", "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
            z.write(tmp, os.path.basename(tmp))
        os.remove(tmp)
        write(os.path.join(OUTD, "large_unified_smallest.csv"), small, F + ["quirk"])
        for L in quirk_levels:
            write_gate_lists([r for r in rows if r["l"] == L], L)
        for L in quirk_levels:                       # one file per level with its Quirk links
            tmp = os.path.join(OUTD, f"large_unified_l{L}_with_quirk.csv")
            write(tmp, [r for r in rows if r["l"] == L], F + ["quirk"])
            with zipfile.ZipFile(tmp + ".zip", "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
                z.write(tmp, os.path.basename(tmp))
            os.remove(tmp)
    nd = sum(status.values())
    print(f"slices finished: {nd} of {sum(KMAX_LEVEL.values())}")
    for L in (2, 3, 4):
        R = [r for r in rows if r["l"] == str(L)]; S = [r for r in small if r["l"] == str(L)]
        st = {s: sum(1 for r in S if r["search_stage"] == s) for s in ("two-group", "gluing")}
        opn = sorted(k for (l, k), d in status.items() if l == L and not d)
        queued = [k for k in range(1, KMAX_LEVEL[L] + 1) if (L, k) not in status]
        print(f"l={L} (N<={NMAX[L]}): {len(R)} factories | {len({(r['n'], r['k'], r['reduced']) for r in R})} classes by [[n,k]] and output"
              f" | {len(S)} output gates, smallest from two-group {st['two-group']}, gluing {st['gluing']}"
              f" | running k={opn} | not started k={queued}")


if __name__ == "__main__":
    lv = [a.split("=")[1] for a in sys.argv if a.startswith("--quirk-levels=")]
    main(with_quirk="--no-quirk" not in sys.argv, quirk_levels=tuple(lv[0].split(",")) if lv else ("2", "3", "4"))
